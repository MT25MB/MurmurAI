def plain_english(name: str, description: str) -> str:
    """Return a short, factual description for the docs table cell."""
    text = re.sub(r"\s+", " ", str(description or "")).strip()
    text = text.replace("|", "/")
    return text[:220] if text else name.replace("_", " ").capitalize()


def fallback_examples(name: str) -> list[str]:
    words = name.replace("_", " ").strip()
    return [words[0].upper() + words[1:]]


def tools_payload() -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    from agent.brain import ALL_TOOLS

    tools: list[dict[str, Any]] = []
    for entry in ALL_TOOLS:
        fn = entry.get("function", {}) if isinstance(entry, dict) else {}
        name = str(fn.get("name") or "").strip()
        if not name:
            continue
        description = str(fn.get("description") or "").strip()
        properties = (fn.get("parameters") or {}).get("properties") or {}
        tools.append({
            "name": name,
            "description": description,
            "parameters": sorted(str(k) for k in properties),
            "examples": EXAMPLE_PHRASES.get(name, fallback_examples(name)),
        })

    categorized: list[dict[str, Any]] = []
    used: set[str] = set()
    for label, summary, prefixes in CATEGORIES:
        entries = [
            tool for tool in tools
            if tool["name"].startswith(prefixes) and tool["name"] not in used
        ]
        for tool in entries:
            used.add(tool["name"])
        categorized.append({
            "category": label,
            "summary": summary,
            "tools": entries,
        })
    leftover = [tool for tool in tools if tool["name"] not in used]
    if leftover:
        categorized.append({
            "category": "More actions",
            "summary": "Other registered local tools.",
            "tools": leftover,
        })
    return tools, categorized


def skills_payload() -> list[dict[str, Any]]:
    from skills.pack_loader import load_packs

    result = []
    for pack_id, pack in sorted(load_packs().items()):
        result.append({
            "id": pack_id,
            "appName": pack.app_name,
            "hotkeys": dict(sorted(pack.hotkeys.items())),
            "terminology": dict(sorted(pack.terminology.items())),
            "promptContext": pack.prompt_context,
            "source": pack.source,
        })
    return result


def extras_payload() -> tuple[list[dict[str, str]], list[dict[str, Any]]]:
    from audio.pronunciation import DEFAULT_PRONUNCIATIONS
    from system.settings_tools import DEFAULT_SETTINGS

    pronunciations = [
        {"term": term, "spoken": spoken}
        for term, spoken in sorted(DEFAULT_PRONUNCIATIONS.items())
    ]
    settings = [
        {"key": key, "default": default}
        for key, default in sorted(DEFAULT_SETTINGS.items())
        if isinstance(default, (bool, float, int, str))
    ]
    return pronunciations, settings


def ts_literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def render_ts(
    categorized: list[dict[str, Any]],
    skills: list[dict[str, Any]],
    pronunciations: list[dict[str, str]],
    settings: list[dict[str, Any]],
) -> str:
    return f"""// {HEADER}
// Regenerate with: python scripts/generate_docs.py

export interface VoiceTool {{
  name: string;
  description: string;
  parameters: string[];
  examples: string[];
}}

export interface ToolCategory {{
  category: string;
  summary: string;
  tools: VoiceTool[];
}}

export interface SkillPack {{
  id: string;
  appName: string;
  hotkeys: Record<string, string>;
  terminology: Record<string, string>;
  promptContext: string;
  source: string;
}}

export interface Pronunciation {{
  term: string;
  spoken: string;
}}

export interface SettingDefault {{
  key: string;
  default: boolean | number | string;
}}

export interface GeneratedReference {{
  categories: ToolCategory[];
  skills: SkillPack[];
  pronunciations: Pronunciation[];
  settings: SettingDefault[];
  settingPhrases: {{ group: string; phrases: string[] }}[];
}}

export const generatedReference: GeneratedReference = {{
  categories: {ts_literal(categorized)},
  skills: {ts_literal(skills)},
  pronunciations: {ts_literal(pronunciations)},
  settings: {ts_literal(settings)},
  settingPhrases: {ts_literal([{"group": group, "phrases": phrases} for group, phrases in SETTING_PHRASES])},
}};

export default generatedReference;
"""


def render_md(
    categorized: list[dict[str, Any]],
    skills: list[dict[str, Any]],
    pronunciations: list[dict[str, str]],
    settings: list[dict[str, Any]],
) -> str:
    lines = [
        "# Murmur AI voice command reference",
        "",
        f"<!-- {HEADER} -->",
        "",
        "These commands run locally. Say them out loud, or type them in the HUD.",
        "Everything below is generated from the tool schemas, built-in skill packs,",
        "and default configuration in this exact release.",
        "",
        "## Contents",
        "",
    ]
    for group in categorized:
        anchor = re.sub(r"[^a-z0-9]+", "-", group["category"].lower()).strip("-")
        lines.append(f"- [{group['category']}](#{anchor})")
    lines += [
        "- [Voice settings](#voice-settings)",
        "- [Built-in skill packs](#built-in-skill-packs)",
        "- [Default pronunciations](#default-pronunciations)",
        "- [Configuration defaults](#configuration-defaults)",
        "- [Keeping this reference current](#keeping-this-reference-current)",
        "",
    ]

    for group in categorized:
        lines += [
            f"## {group['category']}",
            "",
            group["summary"],
            "",
            "| Command | What it does | Say it like this |",
            "| --- | --- | --- |",
        ]
        for tool in group["tools"]:
            examples = "<br>".join(f"\"{example}\"" for example in tool["examples"])
            lines.append(
                f"| `{tool['name']}` | {plain_english(tool['name'], tool['description'])} | {examples} |"
            )
        lines.append("")

    lines += [
        "## Voice settings",
        "",
        "These phrases are matched locally before the model is called, so they work",
        "even when Ollama is offline.",
        "",
        "| Area | Say it like this |",
        "| --- | --- |",
    ]
    for group_name, phrases in SETTING_PHRASES:
        examples = ", ".join('"' + phrase + '"' for phrase in phrases)
        lines.append(f"| {group_name} | {examples} |")
    lines += [
        "",
        "## Built-in skill packs",
        "",
        "Skill packs carry hotkeys and terminology only. They never contain executable code.",
        "",
    ]
    for skill in skills:
        lines += [f"### {skill['appName']} (`{skill['id']}`)", "", skill["promptContext"] or "No prompt context.", "", "| Action | Shortcut |", "| --- | --- |"]
        for action, shortcut in skill["hotkeys"].items():
            lines.append(f"| {action} | `{shortcut}` |")
        if skill["terminology"]:
            lines += ["", "| Term | Meaning |", "| --- | --- |"]
            for term, meaning in skill["terminology"].items():
                lines.append(f"| {term} | {meaning} |")
        lines.append("")

    lines += [
        "## Default pronunciations",
        "",
        "Murmur normalizes these terms before local text-to-speech. Add your own with",
        "\"pronounce X as Y\" or in `~/.murmur-ai/pronunciations.json`.",
        "",
        "| Term | Spoken as |",
        "| --- | --- |",
    ]
    for item in pronunciations:
        lines.append(f"| {item['term']} | {item['spoken']} |")

    lines += [
        "",
        "## Configuration defaults",
        "",
        "Preferences live in `~/.murmur-ai/config.json`. Launch-at-login is opt-in,",
        "and the OS registration is the source of truth.",
        "",
        "| Setting | Default |",
        "| --- | --- |",
    ]
    for item in settings:
        lines.append(f"| `{item['key']}` | `{json.dumps(item['default'])}` |")

    lines += [
        "",
        "## Keeping this reference current",
        "",
        "Run `python scripts/generate_docs.py` after changing a tool schema, skill pack,",
        "pronunciation, or setting default. `scripts/verify-all.ps1` and `verify-all.sh`",
        "run `python scripts/generate_docs.py --check`, which fails if these files are stale.",
        "The same generated data feeds the website's command and skill explorer.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="fail if the generated files are missing or out of date",
    )
    args = parser.parse_args()

    tools, categorized = tools_payload()
    skills = skills_payload()
    pronunciations, settings = extras_payload()
    outputs = {
        DOC_PATH: render_md(categorized, skills, pronunciations, settings),
        TS_PATH: render_ts(categorized, skills, pronunciations, settings),
    }

    if args.check:
        stale = []
        for path, content in outputs.items():
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        if stale:
            print("Generated documentation is out of date: " + ", ".join(stale), file=sys.stderr)
            print("Run: python scripts/generate_docs.py", file=sys.stderr)
            return 1
        print(f"Docs check passed: {len(tools)} tools, {len(skills)} skill packs, "
              f"{len(pronunciations)} pronunciations")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")
    print(f"Generated {len(tools)} tools, {len(skills)} skill packs, "
          f"{len(pronunciations)} pronunciations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
